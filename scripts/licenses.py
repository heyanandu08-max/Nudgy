#!/usr/bin/env python3
"""Writes backend/legal/licenses.md: every open-source package Nudgy ships, with its license.

Sources: `cargo metadata` (the desktop app's Rust crates), app/package-lock.json (production
npm packages, fonts included) and the backend's installed Python requirements.
Exits non-zero if a package has no license or a strong copyleft one (GPL/AGPL), which a
closed-source app can't ship.

Run from the repo root after changing dependencies:  python3 scripts/licenses.py
(the backend venv must exist: backend/.venv)
"""

from __future__ import annotations

import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "backend" / "legal" / "licenses.md"
BLOCKED = re.compile(r"\b(A?GPL)", re.I)  # LGPL/MPL are fine for linking; GPL/AGPL are not


def rust() -> list[tuple[str, str, str]]:
    meta = json.loads(
        subprocess.check_output(
            ["cargo", "metadata", "--format-version", "1", "--locked"],
            cwd=ROOT / "app" / "src-tauri",
        )
    )
    ours = {p["id"] for p in meta["packages"] if p.get("source") is None}
    return sorted(
        (p["name"], p["version"], p.get("license") or "")
        for p in meta["packages"]
        if p["id"] not in ours
    )


def npm() -> list[tuple[str, str, str]]:
    lock = json.loads((ROOT / "app" / "package-lock.json").read_text())
    rows = []
    for path, p in lock["packages"].items():
        if not path or p.get("dev") or p.get("devOptional"):
            continue
        name = path.split("node_modules/")[-1]
        lic = p.get("license") or ""
        if not lic:
            pkg = ROOT / "app" / path / "package.json"
            if pkg.exists():
                lic = json.loads(pkg.read_text()).get("license", "")
        rows.append((name, p.get("version", ""), lic if isinstance(lic, str) else str(lic)))
    return sorted(set(rows))


PY_REQ = re.compile(r"^([A-Za-z0-9_.\-]+)")


def python() -> list[tuple[str, str, str]]:
    py = ROOT / "backend" / ".venv" / "bin" / "python"
    code = r"""
import json, re
from importlib.metadata import distribution, PackageNotFoundError
seen, rows, todo = set(), [], ["nudgy-backend"]
while todo:
    name = todo.pop()
    key = re.sub(r"[-_.]+", "-", name).lower()
    if key in seen: continue
    seen.add(key)
    try: d = distribution(name)
    except PackageNotFoundError: continue
    for r in d.requires or []:
        if "extra ==" in r: continue
        todo.append(re.match(r"[A-Za-z0-9_.\-]+", r).group(0))
    if key == "nudgy-backend": continue
    m = d.metadata
    lic = m.get("License-Expression") or ""
    if not lic:
        cls = [c.split(" :: ")[-1] for c in m.get_all("Classifier") or [] if c.startswith("License ::")]
        lic = "; ".join(cls) or (m.get("License") or "").split("\n")[0][:60]
    rows.append((d.metadata["Name"], d.version, lic))
print(json.dumps(sorted(rows)))
"""
    return [tuple(r) for r in json.loads(subprocess.check_output([str(py), "-c", code]))]


def table(rows: list[tuple[str, str, str]]) -> str:
    lines = ["| Package | Version | License |", "| --- | --- | --- |"]
    lines += [f"| {n} | {v} | {lic or 'unknown'} |" for n, v, lic in rows]
    return "\n".join(lines)


def main() -> int:
    sections = {
        "Desktop app (Rust)": rust(),
        "Desktop app (JavaScript, fonts included)": npm(),
        "Server (Python)": python(),
    }
    problems = [
        f"{where}: {n} {v} ({lic or 'no license'})"
        for where, rows in sections.items()
        for n, v, lic in rows
        if not lic or (BLOCKED.search(lic) and not re.search(r"\bOR\b|/", lic))
    ]
    body = [
        "<!-- Generated by scripts/licenses.py. Do not edit by hand. Served at /licenses. -->",
        "# Open-source licenses",
        "",
        "Nudgy is built with these open-source packages. Each remains under its own license; "
        "the full license texts ship with each package. The fonts (Poppins, Lora, JetBrains "
        "Mono) are under the SIL Open Font License 1.1. Nudgy's logo, icons and illustrations "
        "are our own work.",
    ]
    for where, rows in sections.items():
        body += ["", f"## {where}", "", table(rows)]
    OUT.write_text("\n".join(body) + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}: {sum(len(r) for r in sections.values())} packages")
    if problems:
        print("License problems:\n  " + "\n  ".join(problems), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
